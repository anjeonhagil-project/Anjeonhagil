CREATE TABLE public.notices (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(200) NOT NULL,
    content text NOT NULL,
    is_published boolean NOT NULL DEFAULT false,
    published_at timestamptz,
    created_by uuid
        REFERENCES public.admins(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT ck_notices_published_at
        CHECK (is_published = false OR published_at IS NOT NULL)
);

COMMENT ON TABLE public.notices IS
'사용자 공지사항 및 관리자 공지 CRUD 데이터.';

CREATE TABLE public.inquiries (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id uuid NOT NULL
        REFERENCES public.users(id) ON DELETE CASCADE,
    category varchar(50) NOT NULL,
    title varchar(200) NOT NULL,
    content text NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'received',
    answer_content text,
    answered_by uuid
        REFERENCES public.admins(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    answered_at timestamptz,
    updated_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT ck_inquiries_status
        CHECK (
            status IN ('received','in_review','answered')
            AND (
                status <> 'answered'
                OR (answer_content IS NOT NULL AND answered_at IS NOT NULL)
            )
        )
);

COMMENT ON TABLE public.inquiries IS
'사용자 문의 원본과 관리자 답변/처리상태.';

